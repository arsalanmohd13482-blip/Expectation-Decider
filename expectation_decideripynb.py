"""### Part 3: Random Variable & Probability Distribution"""

# Define a random variable representing the "Number of students passing the final exam" out of 3 randomly selected students.
# 1.Calculate the probability of student who pass in the exam.
total_students = len(student_data)
pass_students = student_data[student_data['final_exam_pass'] == 'Pass']
count_pass_student = len(pass_student)
p = count_pass_student / total_students

# 2.Define the parameter.
n = 3
x_values = [0, 1, 2, 3]
probabilities = []

# For solving the combination formula .
import math

# 3.Calculate the P(X=x).
for x in x_values:
    combinations = math.comb(n, x)
    prob_x = combinations * (p**x) * ((1 - p)**(n - x))
    probabilities.append(prob_x)

# Construct the probability table.
distribution_table = pd.DataFrame({
    'X (Number of Students Passing)': x_values,
    'P(X = x)': probabilities
})

# 5. Calculate Mean and Variance
mean_x = n * p
variance_x = n * p * (1 - p)

# Display Results
print("Probability Distribution Table:")
print("-" * 40)
print(distribution_table.to_markdown(index=False))
print("\nStatistical Moments:")
print("-" * 40)
print(f"Mean (E[X]): {mean_x:.4f}")
print(f"Variance (Var(X)): {variance_x:.4f}")

