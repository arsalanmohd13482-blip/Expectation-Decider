"""### Part 7: Bayes Theorem Application"""

# Use Bayes Theorem to find the probability that a student passed the exam given they had high attendance.
# Given probabilities
p_high_attendance_given_pass = 0.70
p_high_attendance_given_fail = 0.40
p_high_attendance = 0.60

# Calculate P(Pass)
# P(H) = P(H|Pass)P(Pass) + P(H|Fail)P(Fail)

p_pass = (
    p_high_attendance - p_high_attendance_given_fail
) / (
    p_high_attendance_given_pass - p_high_attendance_given_fail
)

# Calculate P(Fail)
p_fail = 1 - p_pass

# Apply Bayes' Theorem
p_pass_given_high_attendance = (
    p_high_attendance_given_pass * p_pass
) / p_high_attendance

print(f"P(Pass) = {p_pass:.4f}")
print(f"P(Fail) = {p_fail:.4f}")
print(f"P(Pass | High Attendance) = {p_pass_given_high_attendance:.4f}")
print(f"Percentage = {p_pass_given_high_attendance:.2%}")